 const external=[];page.on('request',request=>{if(new URL(request.url()).origin!==new URL(base).origin)external.push(request.url())});
 await page.addInitScript(()=>{Object.defineProperty(navigator,'clipboard',{value:{writeText:()=>Promise.reject(Error('blocked'))},configurable:true})});
 await page.goto(base+'/?lang=ru&utm_source=test-source');await page.locator('[data-category="coffee"]').click();
