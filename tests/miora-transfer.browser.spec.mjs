import { test,expect } from '@playwright/test';
const base=process.env.POCITEL_TEST_BASE_URL??'http://127.0.0.1:8088';
for(const lang of ['tr','en','ru'])for(const width of [320,390,1280])test(`Miora navigation/list ${lang} ${width}px`,async({page},testInfo)=>{
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.setViewportSize({width,height:844});await page.goto(base+'/?lang='+lang);
 await page.locator('#toggle-search').click();await page.locator('#search').fill('no-such-drink-123');
 await expect(page.locator('#results .feed-post')).toHaveCount(0);
 const category=page.locator('[data-category="coffee"]');await category.focus();await page.keyboard.press('Enter');
 await expect(page.locator('#search')).toHaveValue('');await expect(category).toBeFocused();
 await expect(page.locator('#post-cappuccino')).toBeVisible();
 await expect.poll(async()=>page.locator('#results .feed-post').first().evaluate(node=>node.getBoundingClientRect().top)).toBeLessThan(700);
 const original=await page.locator('#results .feed-post').evaluateAll(nodes=>nodes.map(node=>node.id));
 await page.locator('button[data-menu-view="list"]').click();
 await expect(page.locator('#results')).toHaveAttribute('data-menu-view','list');
 expect(await page.locator('#results .feed-post').evaluateAll(nodes=>nodes.map(node=>node.id))).toEqual(original);
 expect((await page.locator('#post-cappuccino .post-media img').boundingBox()).height).toBeLessThanOrEqual(94);
 if(lang==='ru'&&width===390)await page.screenshot({path:testInfo.outputPath('compact-menu.png')});
 await page.locator('#post-cappuccino [data-add="cappuccino"]').click();
 await page.locator('#post-cappuccino [data-save="cappuccino"]').click();
 await page.locator('#post-cappuccino .post-media').click();await expect(page.locator('#post-viewer')).toBeVisible();await page.locator('#close-post').click();
 await page.reload();await expect(page.locator('#results')).toHaveAttribute('data-menu-view','list');
 await expect(page.locator('#selection-bar [data-count]')).toHaveText('1');
 await page.locator('[data-category="coffee"]').click();await expect(page.locator('#post-cappuccino [data-save="cappuccino"]')).toHaveAttribute('aria-pressed','true');
 await page.locator('button[data-menu-view="photos"]').click();await expect(page.locator('#results')).toHaveAttribute('data-menu-view','photos');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width+2);expect(errors).toEqual([]);
});
